import { useMemo, useState } from "react";
import { Link } from "react-router-dom";
import { useApi } from "../lib/api.ts";
import { Card, Loading, Fresh, Seg, Notice, Disclaimer } from "../components/ui.tsx";
import { RankingPanel } from "../components/RankingPanel.tsx";
import { SetupTable } from "./Overview.tsx";
import { SetupCard } from "./StockDetail.tsx";

/* eslint-disable @typescript-eslint/no-explicit-any */
export default function Technical() {
  const s = useApi<{ asOf: string; setups: any[] }>("/setups");
  const [side, setSide] = useState<"buy" | "sell">("buy");
  const [type, setType] = useState("");
  const [sel, setSel] = useState<any>(null);
  const rows = useMemo(() => (s.data?.setups ?? []).filter((x) => x.side === side && (!type || x.type === type)), [s.data, side, type]);
  const types = [...new Set((s.data?.setups ?? []).filter((x) => x.side === side).map((x) => x.type))];
  return (
    <div className="page">
      <div className="page-head"><div><h1>Technical Analysis</h1><p>Algorithmic setups, support/resistance and trading-strategy rankings across liquid NEPSE stocks. <Fresh date={s.data?.asOf} /></p></div></div>
      <Notice>Setups are generated by fixed rules from end-of-day data (no intraday). Each has an entry zone, stop-loss, targets, risk/reward and invalidation. NEPSE is long-only, so "sell" signals mean protect or avoid. Open a stock and use its Backtest tab to see how a rule has performed on that stock historically.</Notice>
      <div className="grid g3">
        <Card title="Active setups" className="span2" flush actions={<>
          <Seg value={side} onChange={(v) => { setSide(v); setType(""); }} options={[{ key: "buy", label: "Buy setups" }, { key: "sell", label: "Exit / avoid" }]} />
          <select className="input" value={type} onChange={(e) => setType(e.target.value)}><option value="">All types</option>{types.map((t) => <option key={t}>{t}</option>)}</select>
        </>}>
          {s.loading && !s.data ? <Loading label="Scanning all liquid stocks" /> : (
            <SetupTable rows={rows.slice(0, 80)} onSelect={setSel} />
          )}
        </Card>
        <Card title={sel ? `${sel.symbol} · ${sel.type}` : "Setup details"} actions={sel && <Link className="btn sm" to={`/stocks/${sel.symbol}`}>Open stock</Link>}>
          {sel ? <SetupCard s={sel} /> : <p className="muted small">Select a setup to see the full reasoning, levels and invalidation conditions.</p>}
          <Disclaimer />
        </Card>
      </div>
      <Card title="Trading strategy rankings" sub="Momentum and swing models (separate from investing models)">
        <RankingPanel kinds={["trading"]} defaultKey="swing" />
      </Card>
    </div>
  );
}
